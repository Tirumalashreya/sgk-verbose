@lru_cache(maxsize=1)
def _sorted_terms() -> list[tuple[str, str, re.Pattern]]:
    """Sort terms by length descending, with precompiled word-boundary regexes."""
    # Telugu Unicode block: \u0c00-\u0c7f
    items = sorted(VAISHNAVA_INLINE_TERMS.items(), key=lambda kv: len(kv[0]), reverse=True)
    compiled = []
    for term, orig in items:
        # Word boundary in Telugu script: not preceded or followed by a Telugu char
        pat = re.compile(r"(?<![ఀ-౿])" + re.escape(term) + r"(?![ఀ-౿])")
        compiled.append((term, orig, pat))
    return compiled


def detect_inline_terms(norm_transcript: str, existing_shlokas: list) -> list[dict]:
    """Scans norm_transcript for Sri Vaishnava terms outside existing full verse spans.
    
    Returns a list of inline term dicts compatible with shlokas:
      - is_inline: True (forces inline rendering in formatting_agent)
      - text: Exact verbatim match from transcript
      - original: Tamil / Devanagari script for bracket display
    """
    if not norm_transcript:
        return []

    # Spans already claimed by full recited verses (must never be broken)
    occupied: list[tuple[int, int]] = []
    for s in existing_shlokas:
        for a, b in s.get("occurrences", []):
            occupied.append((a, b))
        if "start_index" in s and "end_index" in s:
            occupied.append((s["start_index"], s["end_index"]))

    terms = _sorted_terms()
    found: list[dict] = []

    for term, orig, pat in terms:
        for m in pat.finditer(norm_transcript):
            start, end = m.start(), m.end()
            # If this occurrence overlaps any existing verse or already tagged inline term, skip it
            if any(a < end and start < b for a, b in occupied):
                continue
            occupied.append((start, end))

            # Determine script language
            is_sanskrit = any('\u0900' <= ch <= '\u097f' for ch in orig)
            if not is_sanskrit:
                # Tamil script in brackets is not required by user; leave as natural Telugu text
                continue
            lang = "Sanskrit"

            found.append({
                "language": lang,
                "type": "InlineTerm",
                "text": norm_transcript[start:end],  # 100% verbatim from transcript!
                "original": orig,
                "is_inline": True,
                "confidence": 1.0,
                "verified": True,
                "start_index": start,
                "end_index": end,
                "occurrences": [[start, end]],
            })

    return sorted(found, key=lambda s: s["start_index"])
